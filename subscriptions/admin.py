@admin.register(Subscription)
class SubscriptionAdmin(admin.ModelAdmin):
    list_display = (
        "user",
        "product",
        "kind",
        "status",
        "plan",
        "display_starts_at",
        "display_expires_at",
    )
    @admin.display(description="شروع اعتبار")
    def display_starts_at(self, obj):
        if obj.is_waiting_for_activation:
            return "پس از اولین فعال‌سازی"
        return obj.starts_at

    @admin.display(description="انقضای اعتبار")
    def display_expires_at(self, obj):
        if obj.is_waiting_for_activation:
            return "پس از اولین فعال‌سازی"
        return obj.expires_at

    list_filter = ("kind", "status", "product")
    search_fields = (
        "user__username",
        "user__email",
        "product__name",
        "plan__name",
    )
    autocomplete_fields = (
        "user",
        "product",
        "plan",
        "trial_redemption",
    )
    list_select_related = (
        "user",
        "product",
        "plan",
        "trial_redemption",
    )
    readonly_fields = ("created_at", "updated_at")

    def get_exclude(self, request, obj=None):
        # Dates are generated by the server when a subscription is created.
        # Never accept start/expiry dates from the admin form.
        excluded = list(super().get_exclude(request, obj) or ())
        if obj is None:
            excluded.extend(("starts_at", "expires_at"))
        return tuple(dict.fromkeys(excluded))

    def get_readonly_fields(self, request, obj=None):
        readonly = list(super().get_readonly_fields(request, obj))
        if obj is not None:
            # Historical subscription dates must not be editable.
            readonly.extend(("starts_at", "expires_at"))
        return tuple(readonly)

    def save_model(self, request, obj, form, change):
        if not change:
            now = timezone.now()

            if obj.kind == Subscription.Kind.PAID:
                if obj.plan is None:
                    raise ValidationError(
                        {"plan": "A paid subscription must have a plan."}
                    )
                obj.starts_at = now
                obj.expires_at = _add_plan_duration(now, obj.plan)
                obj.trial_redemption = None
            elif obj.kind == Subscription.Kind.TRIAL:
                if obj.trial_redemption is None:
                    raise ValidationError(
                        {
                            "trial_redemption": (
                                "A trial subscription must reference its "
                                "trial redemption record."
                            )
                        }
                    )
                # Use the actual trial period already recorded, not a date
                # that an administrator can choose manually.
                obj.starts_at = obj.trial_redemption.started_at
                obj.expires_at = obj.trial_redemption.ends_at
                obj.plan = None

            obj.full_clean()

        super().save_model(request, obj, form, change)


@admin.register(SubscriptionRenewal)
class SubscriptionRenewalAdmin(admin.ModelAdmin):
    list_display = (
        "subscription",
        "payment_reference",
        "amount_minor_units",
        "currency",
        "previous_expires_at",
        "new_expires_at",
        "created_at",
    )
    list_filter = ("currency", "created_at")
    search_fields = (
        "payment_reference",
        "subscription__user__email",
        "subscription__user__username",
    )
    list_select_related = (
        "subscription",
        "subscription__user",
        "subscription__product",
    )
    readonly_fields = (
        "subscription",
        "payment_reference",
        "previous_expires_at",
        "new_expires_at",
        "amount_minor_units",
        "currency",
        "created_at",
    )

    def has_add_permission(self, request):
        return False

    def has_change_permission(self, request, obj=None):
        return False
