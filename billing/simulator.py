"""Credential-free local payment simulator for development only.

This does not contact Zarinpal and must never be enabled in production.
"""
import uuid

from django.conf import settings
from django.contrib.auth.decorators import login_required
from django.db import transaction
from django.shortcuts import get_object_or_404, redirect, render
from django.views.decorators.http import require_GET, require_POST

from catalog.models import Plan
from .models import PaymentAttempt, PaymentOrder
from .services import (
    OrderCreationError,
    PaymentAttemptCreationError,
    PaymentFinalizationError,
    create_payment_attempt,
    create_payment_order,
    finalize_payment,
)


def _simulator_enabled():
    return bool(settings.DEBUG and getattr(settings, "NEBULA_MOCK_PAYMENTS", False))


def _disabled_response(request):
    return render(
        request,
        "billing/payment_result.html",
        {
            "success": False,
            "message": "شبیه‌ساز پرداخت فقط در محیط توسعه و با فعال‌بودن پرداخت آزمایشی در دسترس است.",
        },
        status=404,
    )


@login_required
@require_POST
def start_local_simulation(request, plan_id):
    """Create a normal pending order and show a local success/failure choice."""
    if not _simulator_enabled():
        return _disabled_response(request)

    plan = get_object_or_404(
        Plan.objects.select_related("product"),
        pk=plan_id,
        is_active=True,
        product__is_active=True,
    )
    try:
        order = PaymentOrder.objects.filter(
            user=request.user,
            plan=plan,
            status=PaymentOrder.Status.PENDING,
            subscription__isnull=True,
        ).order_by("-created_at").first()
        if order is None:
            order = create_payment_order(
                user=request.user,
                plan_id=plan.pk,
                idempotency_key=uuid.uuid4(),
            )

        attempt = create_payment_attempt(
            user=request.user,
            order_id=order.pk,
            provider="local_simulator",
            idempotency_key=uuid.uuid4(),
        )
        # The reference is generated by the server and never supplied by the browser.
        attempt.provider_reference = f"local-sim-{attempt.pk}"
        attempt.status = PaymentAttempt.Status.PENDING
        attempt.save(update_fields=["provider_reference", "status", "updated_at"])
    except (OrderCreationError, PaymentAttemptCreationError, ValueError) as exc:
        return render(
            request,
            "billing/payment_result.html",
            {"success": False, "message": f"شروع شبیه‌سازی پرداخت ممکن نشد: {exc}"},
            status=400,
        )

    return redirect("billing:local_simulator", attempt_id=attempt.pk)


@login_required
@require_GET
def local_simulator(request, attempt_id):
    """Show the simulated gateway page for the current user's attempt only."""
    if not _simulator_enabled():
        return _disabled_response(request)

    attempt = get_object_or_404(
        PaymentAttempt.objects.select_related("order", "order__plan", "order__plan__product"),
        pk=attempt_id,
        order__user=request.user,
        provider="local_simulator",
    )
    if attempt.status == PaymentAttempt.Status.SUCCEEDED:
        return render(request, "billing/payment_result.html", {
            "success": True,
            "message": "این پرداخت آزمایشی قبلاً با موفقیت تکمیل شده است.",
            "order": attempt.order,
            "reference": attempt.provider_reference,
            "sandbox": True,
        })
    return render(request, "billing/local_simulator.html", {"attempt": attempt})


@login_required
@require_POST
def complete_local_simulation(request, attempt_id):
    """Simulate a successful or failed gateway response in development only."""
    if not _simulator_enabled():
        return _disabled_response(request)

    attempt = get_object_or_404(
        PaymentAttempt.objects.select_related("order", "order__plan", "order__plan__product"),
        pk=attempt_id,
        order__user=request.user,
        provider="local_simulator",
    )
    action = request.POST.get("simulation_result")
    if action not in {"success", "failure"}:
        return render(request, "billing/local_simulator.html", {
            "attempt": attempt,
            "error": "نتیجه شبیه‌سازی معتبر نیست.",
        }, status=400)

    if action == "failure":
        if attempt.status in (PaymentAttempt.Status.CREATED, PaymentAttempt.Status.PENDING):
            attempt.status = PaymentAttempt.Status.FAILED
            attempt.save(update_fields=["status", "updated_at"])
        return render(request, "billing/payment_result.html", {
            "success": False,
            "message": "پرداخت ناموفق به‌صورت آزمایشی شبیه‌سازی شد؛ سفارش فعال نشده است.",
            "order": attempt.order,
            "sandbox": True,
        })

    try:
        with transaction.atomic():
            finalized = finalize_payment(
                attempt_id=attempt.pk,
                provider_reference=attempt.provider_reference,
                confirmed_amount_minor_units=attempt.amount_minor_units,
                confirmed_currency=attempt.currency,
            )
    except PaymentFinalizationError as exc:
        return render(request, "billing/payment_result.html", {
            "success": False,
            "message": f"تکمیل پرداخت آزمایشی ممکن نشد: {exc}",
            "order": attempt.order,
            "sandbox": True,
        }, status=400)

    return render(request, "billing/payment_result.html", {
        "success": True,
        "message": "پرداخت آزمایشی با موفقیت شبیه‌سازی شد؛ سفارش و دسترسی در پایگاه داده ثبت شدند.",
        "order": attempt.order,
        "reference": attempt.provider_reference,
        "sandbox": True,
        "license_key": getattr(finalized, "issued_license_key", None),
    })
